static bool error(NativeScriptDiagnostic* diagnostic,NativeScriptSourceSpan source,const char* message)
{
    diagnostic->source=source;
    snprintf(diagnostic->message,sizeof(diagnostic->message),"%s",message);
    return false;
}

uint32_t nativeScriptEvents_Count(void)
{
    return (uint32_t)(sizeof(events)/sizeof(events[0]));
}

const NativeScriptEventDescriptor* nativeScriptEvents_Descriptor(uint32_t id)
{
    return id<nativeScriptEvents_Count() ? &events[id] : NULL;
}

static const NativeScriptEventDescriptor* lookup(unsigned context,unsigned kind,
    const NativeScriptSourceTree* tree,NativeScriptSourceSpan name,uint32_t* id)
{
    for (uint32_t i=0;i<nativeScriptEvents_Count();++i)
        if (events[i].context==context && events[i].kind==kind &&
            nativeScriptSource_SpanEquals(tree,name,events[i].name)) { *id=i;return &events[i]; }
    return NULL;
}

static bool unsigned_number(const NativeScriptSourceTree* tree,NativeScriptSourceSpan span,
    uint32_t* at,uint32_t* value)
{
    const char* text=tree->source+span.offset;uint32_t count=0;
    *value=0;
    while (*at<span.length && text[*at]>='0' && text[*at]<='9') {
        uint32_t digit=(uint32_t)(text[(*at)++]-'0');
        if (*value>(UINT32_MAX-digit)/10) return false;
        *value=*value*10+digit;++count;
    }
    return count!=0;
}

static bool motion_name(const NativeScriptSourceTree* tree,NativeScriptSourceSpan name,
    uint32_t* motion,NativeScriptSourceSpan* phase)
{
    const char* text=tree->source+name.offset;
    if (name.length<8 || memcmp(text,"state_",6)) return false;
    uint32_t at=6;
    if (!unsigned_number(tree,name,&at,motion) || *motion>UINT16_MAX ||
        at==name.length || text[at++]!='_') return false;
    *phase=name;phase->offset+=at;phase->column+=at;phase->length-=at;
    return true;
}

static bool article_state(const NativeScriptSourceTree* tree,uint32_t owner,
    const NativeScriptSourceNode* state,uint32_t* id,NativeScriptDiagnostic* diagnostic)
{
    NativeScriptExpressionToken tokens[8];uint32_t count=0;
    const NativeScriptSourceNode* article=&tree->nodes[owner];
    if (!nativeScriptExpression_Tokenize(tree->source,tree->source_bytes,article->value,tokens,8,&count,diagnostic)) return false;
    if (count!=3 || tokens[0].kind!=NativeScriptToken_Name ||
        !nativeScriptSource_SpanEquals(tree,tokens[0].source,"states") ||
        tokens[1].kind!=NativeScriptToken_Integer || tokens[1].bits==0 || tokens[1].bits>32)
        return error(diagnostic,article->value,"Article event ownership requires states N with the source-audited 1..32 range");
    uint32_t states=(uint32_t)tokens[1].bits;
    if (!nativeScriptExpression_Tokenize(tree->source,tree->source_bytes,state->value,tokens,8,&count,diagnostic)) return false;
    if (count<4 || tokens[0].kind!=NativeScriptToken_Integer || tokens[0].bits>=states ||
        !nativeScriptSource_SpanEquals(tree,tokens[1].source,"anim"))
        return error(diagnostic,state->value,"Article state event metadata needs an in-range state N anim A declaration");
    uint32_t at=2;bool negative=false;
    if (tokens[at].kind==NativeScriptToken_Operator &&
        (tokens[at].operation==NativeScriptOp_Subtract || tokens[at].operation==NativeScriptOp_Add)) {
        negative=tokens[at].operation==NativeScriptOp_Subtract;++at;
    }
    if (at>=count || tokens[at].kind!=NativeScriptToken_Integer ||
        (negative ? tokens[at].bits>1 : tokens[at].bits>1023) || at+2!=count)
        return error(diagnostic,state->value,"Unsupported article state callback metadata or animation index");
    *id=(uint32_t)tokens[0].bits;
    return true;
}

bool nativeScriptEvents_Resolve(const NativeScriptSourceTree* tree,const NativeScriptSourceNode* callback,
    NativeScriptEventResolution* result,NativeScriptDiagnostic* diagnostic)
{
    if (!tree || !tree->nodes || !callback || !result || !diagnostic) return false;
    *result=(NativeScriptEventResolution){.event_id=UINT32_MAX,.motion=UINT32_MAX};
    if (callback->kind!=NativeScriptSource_Callback || callback->parent>=tree->count)
        return error(diagnostic,callback->source,"Expected a callback with a source-owned parent");
    const NativeScriptSourceNode* parent=&tree->nodes[callback->parent];
    unsigned context=NativeScriptEvent_Fighter,kind=NativeScriptEvent_FighterHook;
    uint32_t owner=0;
    for (uint32_t at=callback->parent,steps=0;at!=UINT32_MAX && steps<64;++steps) {
        if (at>=tree->count) return error(diagnostic,callback->source,"Invalid callback source ancestry");
        unsigned source_kind=tree->nodes[at].kind;
        if (source_kind==NativeScriptSource_Article || source_kind==NativeScriptSource_Item || source_kind==NativeScriptSource_Effect) {
            owner=at;context=source_kind==NativeScriptSource_Article ? NativeScriptEvent_Article :
                source_kind==NativeScriptSource_Item ? NativeScriptEvent_WorkshopItem : NativeScriptEvent_ModelEffect;
            break;
        }
        at=tree->nodes[at].parent;
    }
    NativeScriptSourceSpan name=callback->name;
    const NativeScriptEventDescriptor* descriptor=NULL;
    if (context==NativeScriptEvent_ModelEffect) {
        if (parent->kind!=NativeScriptSource_Effect)
            return error(diagnostic,callback->source,"Model-effect update must belong directly to its effect declaration");
        kind=NativeScriptEvent_EffectUpdate;
    } else if (context==NativeScriptEvent_WorkshopItem) {
        if (parent->kind!=NativeScriptSource_Item)
            return error(diagnostic,callback->source,"Workshop item callback must belong directly to its item declaration");
        kind=NativeScriptEvent_ItemHook;
    } else if (context==NativeScriptEvent_Article) {
        if (parent->kind==NativeScriptSource_ArticleState) {
            kind=NativeScriptEvent_ArticleState;
            if (!article_state(tree,owner,parent,&result->motion,diagnostic)) return false;
        } else if (parent->kind==NativeScriptSource_Article) {
            const char* text=tree->source+name.offset;
            if (name.length>7 && !memcmp(text,"signal ",7)) {
                result->signal_name=name;result->signal_name.offset+=7;
                result->signal_name.column+=7;result->signal_name.length-=7;
                const char* signal=tree->source+result->signal_name.offset;
                if (!(isalpha((unsigned char)signal[0]) || signal[0]=='_'))
                    return error(diagnostic,name,"Article signal needs an identifier");
                for (uint32_t i=1;i<result->signal_name.length;++i)
                    if (!(isalnum((unsigned char)signal[i]) || signal[i]=='_'))
                        return error(diagnostic,name,"Article signal header has unsupported declarative arguments");
                kind=NativeScriptEvent_ArticleSignal;
                for (uint32_t i=0;i<nativeScriptEvents_Count();++i)
                    if (events[i].kind==kind && events[i].context==context) { descriptor=&events[i];result->event_id=i;break; }
            } else kind=NativeScriptEvent_ArticleLogic;
        } else return error(diagnostic,callback->source,"Article callback must belong directly to its article or state declaration");
    } else {
        if (parent->kind!=NativeScriptSource_Move && parent->kind!=NativeScriptSource_Action)
            return error(diagnostic,callback->source,"Fighter callback must belong directly to an authored move or action");
        NativeScriptSourceSpan phase;
        if (motion_name(tree,name,&result->motion,&phase)) {
            name=phase;kind=NativeScriptEvent_FighterMotion;
        } else if (parent->kind==NativeScriptSource_Move) {
            descriptor=lookup(context,NativeScriptEvent_MovePhase,tree,name,&result->event_id);
            if (descriptor) kind=NativeScriptEvent_MovePhase;
        }
        if (parent->kind==NativeScriptSource_Action && name.length>=8 &&
            !memcmp(tree->source+name.offset,"special_",8))
            return error(diagnostic,name,"Special entry events belong to authored move declarations");
        if (parent->kind==NativeScriptSource_Move &&
            (nativeScriptSource_SpanEquals(tree,name,"grab_catch") ||
             nativeScriptSource_SpanEquals(tree,name,"item_catch") ||
             nativeScriptSource_SpanEquals(tree,name,"grabbed")))
            return error(diagnostic,name,"Capture callback declarations belong to an authored action");
    }
    if (!descriptor) descriptor=lookup(context,kind,tree,name,&result->event_id);
    if (!descriptor)
        return error(diagnostic,callback->name,"Unknown event for this source context, or unsupported declarative event arguments");
    result->descriptor=descriptor;result->owner_node=owner;
    if (!descriptor->signature_supported)
        return error(diagnostic,callback->name,"Event uses mutable native payloads without an accepted script value/output contract");
    return true;
}

bool nativeScriptEvents_Signature(void* unused,const NativeScriptSourceTree* tree,
    const NativeScriptSourceNode* callback,uint32_t owner,NativeScriptIRType* result,
    NativeScriptDefaultReturn* default_return,uint8_t* body_policy,NativeScriptParameterDeclaration* arguments,
    uint32_t capacity,uint32_t* count,NativeScriptDiagnostic* diagnostic)
{
    (void)unused;
    if (!result || !default_return || !body_policy || !count) return false;
    *count=0;
    NativeScriptEventResolution resolution;
    if (!nativeScriptEvents_Resolve(tree,callback,&resolution,diagnostic)) return false;
    if (resolution.owner_node!=owner)
        return error(diagnostic,callback->source,"Event owner differs from the program's declaration scope");
    const NativeScriptEventDescriptor* descriptor=resolution.descriptor;
    if (descriptor->argument_count>capacity || (descriptor->argument_count && !arguments))
        return error(diagnostic,callback->source,"Event parameter capacity exceeded");
    *result=(NativeScriptIRType)descriptor->result_type;
    *body_policy=descriptor->body_policy;
    *default_return=(NativeScriptDefaultReturn){.type=descriptor->result_type};
    if (descriptor->fallthrough==NativeScriptEvent_ReturnArgument) {
        default_return->kind=NativeScriptDefaultReturn_Parameter;
        default_return->argument=descriptor->fallthrough_argument;
    } else if (descriptor->fallthrough!=NativeScriptEvent_ReturnVoid) {
        default_return->kind=NativeScriptDefaultReturn_Constant;
        default_return->bits=descriptor->fallthrough==NativeScriptEvent_ReturnMinusOne ? UINT32_MAX : 0;
    }
    for (uint32_t i=0;i<descriptor->argument_count;++i)
        arguments[i]=(NativeScriptParameterDeclaration){.name={callback->name.offset,0,callback->name.line,callback->name.column},
            .type=(NativeScriptIRType)descriptor->arguments[i].type};
    *count=descriptor->argument_count;
    return true;
}
